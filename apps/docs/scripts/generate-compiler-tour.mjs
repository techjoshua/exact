import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { transform } from '@exactjs/compiler';
import { format } from 'prettier';
import prettierConfig from '../../../prettier.config.mjs';
import { compilerTourAuthoredSource } from './compiler-tour-source.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputFile = resolve(root, 'src/generated/compiler-tour.ts');
const generatedSource = transform(compilerTourAuthoredSource, {
	filename: 'CatalogEditor.tsx'
});
const sourceHash = createHash('sha256').update(compilerTourAuthoredSource).digest('hex');

const moduleSource = `/* Generated by scripts/generate-compiler-tour.mjs. Do not edit. */

/** Authored component used by the compiler lowering tour. */
export const compilerTourAuthoredSource = ${JSON.stringify(compilerTourAuthoredSource)};

/** Exact output emitted by the current @exactjs/compiler transform. */
export const compilerTourGeneratedSource = ${JSON.stringify(generatedSource)};

/** SHA-256 of the authored input, useful when reviewing generated changes. */
export const compilerTourSourceHash = ${JSON.stringify(sourceHash)};
`;

await mkdir(dirname(outputFile), { recursive: true });
await writeFile(
	outputFile,
	await format(moduleSource, { ...prettierConfig, parser: 'typescript' })
);
