import { readFile } from 'node:fs/promises';
import path from 'node:path';

/** Produces the checked-in Go and TypeScript views of the compiler/runtime component ABI. */
export async function compilerAbiOutputs(repositoryRoot) {
	const contract = JSON.parse(
		await readFile(path.join(repositoryRoot, 'scripts/contracts/compiler-abi.json'), 'utf8')
	);
	validateComponentAbi(contract.component);
	const { render, lifecycle, lists, tasks } = contract.component;
	return new Map([
		[
			path.join(
				repositoryRoot,
				'native/typescript-go/overlay/internal/exactcompiler/component_abi_generated.go'
			),
			`// Code generated by scripts/generate-compiler-abi.mjs; DO NOT EDIT.\n\npackage exactcompiler\n\nconst (\n\tcomponentABICompiledRender = ${render}\n\tcomponentABILifecycle      = ${lifecycle}\n\tcomponentABILists          = ${lists}\n\tcomponentABITasks          = ${tasks}\n)\n`
		],
		[
			path.join(repositoryRoot, 'packages/core/src/component/compiled-abi.ts'),
			`// Code generated by scripts/generate-compiler-abi.mjs; DO NOT EDIT.\n\n/** The compiled render arrow only constructs compiler-owned live readers once. */\nexport const compiledComponentRenderABI = ${render};\n\n/** The component registers authored lifecycle or resource-ownership work. */\nexport const compiledComponentLifecycleABI = ${lifecycle};\n\n/** The component uses the general runtime list capability. */\nexport const compiledComponentListsABI = ${lists};\n\n/** The component needs task, interaction, or compatibility execution ownership. */\nexport const compiledComponentTasksABI = ${tasks};\n\n/** Complete capability ABI used by explicitly constructed framework-owned boundary artifacts. */\nexport const generalComponentABI =\n\tcompiledComponentLifecycleABI | compiledComponentListsABI | compiledComponentTasksABI;\n`
		]
	]);
}

function validateComponentAbi(component) {
	const values = ['render', 'lifecycle', 'lists', 'tasks'].map((name) => component?.[name]);
	if (values.some((value) => !Number.isSafeInteger(value) || value <= 0))
		throw new TypeError('compiler component ABI entries must be positive integers');
	if (new Set(values).size !== values.length || values.some((value) => (value & (value - 1)) !== 0))
		throw new TypeError('compiler component ABI entries must be unique bit flags');
}
