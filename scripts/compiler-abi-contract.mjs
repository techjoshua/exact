import { readFile } from 'node:fs/promises';
import path from 'node:path';

/** Produces the checked-in Go and TypeScript views of the compiler/runtime component ABI. */
export async function compilerAbiOutputs(repositoryRoot) {
	const contract = JSON.parse(
		await readFile(path.join(repositoryRoot, 'scripts/contracts/compiler-abi.json'), 'utf8')
	);
	validateComponentAbi(contract.component);
	const adapterApi = JSON.parse(
		await readFile(
			path.join(repositoryRoot, 'packages/react-compat-adapter-api/package.json'),
			'utf8'
		)
	);
	const versions = contract.versions;
	if (
		!versions ||
		['component', 'renderProgram', 'componentLibrary'].some(
			(name) => !Number.isSafeInteger(versions[name]) || versions[name] < 1
		) ||
		typeof versions.compilerProcess !== 'string'
	)
		throw new TypeError('compiler contract versions must be declared');
	const { render, lifecycle, lists, tasks, collections, rangeOutput, contexts } =
		contract.component;
	return new Map([
		[
			path.join(repositoryRoot, 'packages/react-compat-adapter-api/src/package-version.ts'),
			`// Code generated by scripts/generate-compiler-abi.mjs; DO NOT EDIT.\n\n/** Adapter marker package release accepted by dependency-range validation, not a wire-format version. */\nexport const reactCompatAdapterProtocolVersion = '${adapterApi.version}' as const;\n`
		],
		[
			path.join(
				repositoryRoot,
				'native/typescript-go/overlay/internal/exactcompiler/contract_versions_generated.go'
			),
			`// Code generated by scripts/generate-compiler-abi.mjs; DO NOT EDIT.\n\npackage exactcompiler\n\nconst (\n\tcomponentContractVersion = ${versions.component}\n\trenderProgramVersion = ${versions.renderProgram}\n\tcompilerProcessVersion = "${versions.compilerProcess}"\n)\n`
		],
		[
			path.join(repositoryRoot, 'packages/core/src/component/contract-versions.ts'),
			`// Code generated by scripts/generate-compiler-abi.mjs; DO NOT EDIT.\n\n/** Component record version accepted by this ABI generation. */\nexport const componentContractVersion = ${versions.component};\n\n/** Render-program version accepted by this ABI generation. */\nexport const renderProgramVersion = ${versions.renderProgram};\n`
		],
		[
			path.join(repositoryRoot, 'packages/compiler/src/native/contract-versions.ts'),
			`// Code generated by scripts/generate-compiler-abi.mjs; DO NOT EDIT.\n\n/** Component record version emitted by the native compiler. */\nexport const componentContractVersion = ${versions.component};\n\n/** Package build-facts protocol emitted by the compiler. */\nexport const componentLibraryProtocolVersion = ${versions.componentLibrary};\n\n/** Exact native process protocol implemented by this compiler host. */\nexport const nativeCompilerProtocolVersion = '${versions.compilerProcess}';\n`
		],
		[
			path.join(repositoryRoot, 'packages/component-library-policy/src/protocol-version.ts'),
			`// Code generated by scripts/generate-compiler-abi.mjs; DO NOT EDIT.\n\n/** Package build-facts protocol accepted by authorization. */\nexport const componentLibraryProtocolVersion = ${versions.componentLibrary};\n`
		],
		[
			path.join(
				repositoryRoot,
				'native/typescript-go/overlay/internal/exactcompiler/component_abi_generated.go'
			),
			`// Code generated by scripts/generate-compiler-abi.mjs; DO NOT EDIT.\n\npackage exactcompiler\n\nconst (\n\tcomponentABICompiledRender = ${render}\n\tcomponentABILifecycle      = ${lifecycle}\n\tcomponentABILists          = ${lists}\n\tcomponentABITasks          = ${tasks}\n\tcomponentABICollections    = ${collections}\n\tcomponentABIRangeOutput    = ${rangeOutput}\n\tcomponentABIContexts       = ${contexts}\n)\n`
		],
		[
			path.join(repositoryRoot, 'packages/core/src/component/compiled-abi.ts'),
			`// Code generated by scripts/generate-compiler-abi.mjs; DO NOT EDIT.\n\n/** The compiled render arrow only constructs compiler-owned live readers once. */\nexport const compiledComponentRenderABI = ${render};\n\n/** The component registers authored lifecycle or resource-ownership work. */\nexport const compiledComponentLifecycleABI = ${lifecycle};\n\n/** The component uses the general runtime list capability. */\nexport const compiledComponentListsABI = ${lists};\n\n/** The component needs task, interaction, or compatibility execution ownership. */\nexport const compiledComponentTasksABI = ${tasks};\n\n/** State or props can contain Map/Set values that require collection interception. */\nexport const compiledComponentCollectionsABI = ${collections};\n\n/** The component boundary directly observes and reconciles one unstructured output reader. */\nexport const compiledComponentRangeOutputABI = ${rangeOutput};\n\n/** The component reads or publishes values through its logical context chain. */\nexport const compiledComponentContextsABI = ${contexts};\n\n/** Every component capability bit accepted by runtime contract validation. */\nexport const allCompiledComponentABI =\n\tcompiledComponentRenderABI |\n\tcompiledComponentLifecycleABI |\n\tcompiledComponentListsABI |\n\tcompiledComponentTasksABI |\n\tcompiledComponentCollectionsABI |\n\tcompiledComponentRangeOutputABI |\n\tcompiledComponentContextsABI;\n\n/** Conservative non-render ABI used by explicit framework-owned boundary artifacts. */\nexport const generalComponentABI =\n\tcompiledComponentLifecycleABI | compiledComponentListsABI | compiledComponentTasksABI;\n`
		]
	]);
}

function validateComponentAbi(component) {
	const values = [
		'render',
		'lifecycle',
		'lists',
		'tasks',
		'collections',
		'rangeOutput',
		'contexts'
	].map((name) => component?.[name]);
	if (values.some((value) => !Number.isSafeInteger(value) || value <= 0))
		throw new TypeError('compiler component ABI entries must be positive integers');
	if (new Set(values).size !== values.length || values.some((value) => (value & (value - 1)) !== 0))
		throw new TypeError('compiler component ABI entries must be unique bit flags');
}
